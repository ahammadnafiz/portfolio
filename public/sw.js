// Retired. This file previously ran a network-first cache layer that could pin
// visitors to stale HTML. It now unregisters itself and clears what it cached.
// Keep it here (do not delete) until existing registrations have drained.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.map((k) => caches.delete(k))))
      .then(() => self.registration.unregister())
      .then(() => self.clients.matchAll({ type: 'window' }))
      .then((clients) => clients.forEach((c) => c.navigate(c.url)))
  );
});
